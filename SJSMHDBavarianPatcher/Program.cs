using System.Diagnostics;
using AssetsTools.NET;
using PlainAndEasyInjector.ModThingies;

namespace SJSMHDBavarianPatcher;

/// The installer of the Bavarian mod:
///   STEP 1  the game's asset files (texts, textures, audio)   -> AssetsTools.NET (Patcher / Mods.cs), backups in <data>/_modbackup
///   STEP 2  the game's code (Assembly-CSharp.dll, ...)         -> PlainAndEasyInjector (BavarianMod.cs), backups in <data>/_PlainAndEasyInjector_backup
///   STEP 3  files the mod loads while the game runs           -> <data>/Bavaria
/// "revert" undoes all three.
internal static class Program
{
    private const string GameName = "Spooky's Jump Scare Mansion HD Renovation";

    // offered as defaults when the game is not found next to this program
    private static IEnumerable<string> DefaultGameFolders()
    {
        if (OperatingSystem.IsWindows())
        {
            yield return Path.Combine(@"C:\Program Files (x86)\Steam\steamapps\common", GameName);
            yield return Path.Combine(@"C:\Program Files\Steam\steamapps\common", GameName);
        }
        else if (OperatingSystem.IsMacOS())
        {
            string home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
            yield return Path.Combine(home, "Library/Application Support/Steam/steamapps/common", GameName);
        }
        else
        {
            string home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
            yield return Path.Combine(home, ".local/share/Steam/steamapps/common", GameName);
            yield return Path.Combine(home, ".steam/steam/steamapps/common", GameName);
            yield return Path.Combine(home, ".var/app/com.valvesoftware.Steam/.local/share/Steam/steamapps/common", GameName); // Flatpak
        }
    }

    private static async Task<int> Main(string[] args)
    {
        int result = await RunAsync(args);

        // started by double-click (no arguments): keep the window open so the result can be read
        if (args.Length == 0 && !Console.IsInputRedirected)
        {
            Console.WriteLine();
            Console.Write("Press Enter to close.");
            Console.ReadLine();
        }
        return result;
    }

    /// <summary>
    /// Extracts embedded resources (classdata.tpk, Textures, Audio, PlainAndEasyInjector's in-game DLL) to the execution
    /// directory, allowing the patcher to run from a single .exe file.
    /// </summary>
    private static void ExtractEmbeddedResources()
    {
        var assembly = System.Reflection.Assembly.GetExecutingAssembly();
        string baseDir = AppContext.BaseDirectory;

        foreach (string resourceName in assembly.GetManifestResourceNames())
        {
            // PlainAndEasyInjector's in-game DLL ("ingame/..."): always kept up to date, it's what gets installed into the game
            if (resourceName.StartsWith("ingame/", StringComparison.Ordinal))
            {
                string target = Path.Combine(baseDir, "ingame", resourceName.Substring("ingame/".Length));
                using var source = assembly.GetManifestResourceStream(resourceName)!;
                using var buffer = new MemoryStream();
                source.CopyTo(buffer);
                byte[] bytes = buffer.ToArray();
                if (!File.Exists(target) || !File.ReadAllBytes(target).AsSpan().SequenceEqual(bytes))
                {
                    Directory.CreateDirectory(Path.GetDirectoryName(target)!);
                    File.WriteAllBytes(target, bytes);
                }
                continue;
            }

            // Example resource name generated by .NET: "SJSMHDBavarianPatcher.classdata.tpk" or "SJSMHDBavarianPatcher.Textures.file.png"
            string relativePath = resourceName.Substring(assembly.GetName().Name!.Length + 1);

            // Rebuild folder structure by replacing dots for subfolders
            if (relativePath.StartsWith("Textures."))
            {
                relativePath = "Textures" + Path.DirectorySeparatorChar + relativePath.Substring("Textures.".Length);
                int lastDot = relativePath.LastIndexOf('.');
                if (lastDot > relativePath.LastIndexOf(Path.DirectorySeparatorChar))
                {
                    // Restore file extension (e.g., .png) that .NET converted to a dot
                    relativePath = relativePath.Substring(0, lastDot) + "." + relativePath.Substring(lastDot + 1);
                }
            }
            else if (relativePath.StartsWith("Audio."))
            {
                relativePath = "Audio" + Path.DirectorySeparatorChar + relativePath.Substring("Audio.".Length);
                int lastDot = relativePath.LastIndexOf('.');
                if (lastDot > relativePath.LastIndexOf(Path.DirectorySeparatorChar))
                {
                    relativePath = relativePath.Substring(0, lastDot) + "." + relativePath.Substring(lastDot + 1);
                }
            }

            string targetPath = Path.Combine(baseDir, relativePath);
            Directory.CreateDirectory(Path.GetDirectoryName(targetPath)!);

            // Write file to disk only if it doesn't already exist
            if (!File.Exists(targetPath))
            {
                using var stream = assembly.GetManifestResourceStream(resourceName);
                if (stream != null)
                {
                    using var fileStream = File.Create(targetPath);
                    stream.CopyTo(fileStream);
                }
            }
        }
    }

    private static async Task<int> RunAsync(string[] args)
    {
        ExtractEmbeddedResources();
        string? dataDirArg = null;
        var positional = new List<string>();
        for (int i = 0; i < args.Length; i++)
        {
            if (args[i] == "--data" && i + 1 < args.Length) dataDirArg = args[++i];
            else if (args[i] == "--lz4") Patcher.BundleCompressionOverride = AssetBundleCompressionType.LZ4;
            else positional.Add(args[i]);
        }

        string command = positional.Count > 0 ? positional[0].ToLowerInvariant() : "apply";
        if (command is "help" or "-h" or "--help" or "/?")
        {
            PrintUsage();
            return 0;
        }

        if (command == "apply")
        {
            PrintHeader();
        }

        string? dataDir = dataDirArg != null
            ? ResolveDataDir(dataDirArg)
            : FindDataDir() ?? AskForDataDir();
        if (dataDir == null)
        {
            Console.ForegroundColor = ConsoleColor.Red;
            Console.WriteLine("Could not find the game's *_Data folder.");
            Console.WriteLine("Run the program again and enter the game folder, or use: --data \"<game folder>\"");
            Console.ResetColor();
            return 2;
        }
        dataDir = Path.GetFullPath(dataDir);
        string gameRoot = Path.GetDirectoryName(dataDir) ?? dataDir;
        string managedDir = Path.Combine(dataDir, "Managed");
        string scriptDir = AppContext.BaseDirectory;

        string classData = Path.Combine(scriptDir, "classdata.tpk");
        if (!File.Exists(classData))
        {
            Console.ForegroundColor = ConsoleColor.Red;
            Console.WriteLine("classdata.tpk is missing next to this program.");
            Console.ResetColor();
            return 2;
        }

        var patcher = new Patcher(dataDir, classData);

        try
        {
            switch (command)
            {
                case "apply":
                    {
                        Console.ForegroundColor = ConsoleColor.Cyan;
                        Console.WriteLine($"Target Game Folder: {gameRoot}");
                        Console.WriteLine($"Game Data Folder:   {dataDir}");
                        Console.WriteLine("-------------------------------------------");
                        Console.ResetColor();
                        Console.WriteLine("Make sure the game is closed.\n");
                        var clock = Stopwatch.StartNew();

                        // STEP 1: the game's asset files (texts, textures, audio) with AssetsTools.NET
                        Step("--- STEP 1: Patching the game's assets ---");
                        int failures = patcher.Apply(ModList.All);

                        // STEP 2: the game's code (Assembly-CSharp.dll, ...) with PlainAndEasyInjector.
                        // It patches the ORIGINAL files (from its backup if we patched before), so patches never stack.
                        Step("--- STEP 2: Patching the game's code ---");
                        bool codeOk = BavarianMod.Install(managedDir);

                        // STEP 3: files the mod loads while the game runs
                        Step("--- STEP 3: Copying the mod's own files ---");
                        int copied = InstallRuntimeFiles(dataDir);
                        Console.WriteLine($"  {copied} file(s) copied to {Path.Combine(dataDir, RuntimeFolder)}");

                        BavarianTranslationsFromJSON.ReportMissing();
                        Console.WriteLine();
                        Console.WriteLine("-------------------------------------------");
                        if (failures == 0 && codeOk)
                        {
                            Console.ForegroundColor = ConsoleColor.Green;
                            Console.WriteLine($"All processes completed successfully! {ModList.All.Length} asset modification(s) and the code patches applied in {clock.Elapsed.TotalSeconds:0.#} s.");
                            Console.ResetColor();
                            return 0;
                        }
                        else
                        {
                            Console.ForegroundColor = ConsoleColor.Yellow;
                            if (failures > 0) Console.WriteLine($"{failures} asset file(s) failed. Failed files were left in their original state.");
                            if (!codeOk) Console.WriteLine("Patching the game's code failed (see above). The game's DLLs were left as they were.");
                            Console.ResetColor();
                            return 1;
                        }
                    }

                case "revert":
                    {
                        int restored = patcher.Revert();
                        restored += BavarianMod.Uninstall(managedDir);
                        string runtimeFiles = Path.Combine(dataDir, RuntimeFolder);
                        if (Directory.Exists(runtimeFiles)) Directory.Delete(runtimeFiles, recursive: true);
                        Console.WriteLine($"Restored {restored} file(s).");
                        return 0;
                    }

                case "get":
                    {
                        // get <file> <pathId> [field] [--inner <name>]
                        if (positional.Count < 3) { PrintUsage(); return 2; }
                        string file = positional[1];
                        long pathId = long.Parse(positional[2]);
                        string field = positional.Count > 3 && !positional[3].StartsWith("--") ? positional[3] : "";
                        int innerIndex = positional.IndexOf("--inner");
                        string? inner = innerIndex >= 0 && innerIndex + 1 < positional.Count ? positional[innerIndex + 1] : null;
                        Console.WriteLine(patcher.Get(file, inner, pathId, field));
                        return 0;
                    }

                default:
                    PrintUsage();
                    return 2;
            }
        }
        catch (Exception ex)
        {
            Console.ForegroundColor = ConsoleColor.Red;
            Console.WriteLine("Error: " + (ex.Message.Length > 0 ? ex.Message : ex.GetType().Name));
            Console.ResetColor();
            // the details help when reporting a problem
            Console.ForegroundColor = ConsoleColor.DarkGray;
            Console.WriteLine(ex.ToString());
            Console.ResetColor();
            return 1;
        }
    }

    private static void PrintHeader()
    {
        Console.ForegroundColor = ConsoleColor.Cyan;
        Console.WriteLine("===========================================");
        Console.WriteLine("   SJMHD MULTI-FILE PATCHER & INSTALLER");
        Console.WriteLine("===========================================");
        Console.ResetColor();
        Console.WriteLine();
    }

    private static void Step(string title)
    {
        Console.WriteLine();
        Console.ForegroundColor = ConsoleColor.Cyan;
        Console.WriteLine(title);
        Console.ResetColor();
    }

    // ==============================================================================
    // Files the mod itself loads while the game runs (ModExternalAssets loads them from <data folder>/Bavaria/Audio)
    // ==============================================================================
    private const string RuntimeFolder = "Bavaria";
    private static readonly string[] RuntimeAudio = { "EyLeuteHörtAuf.ogg", "SoNeScheißeAua.ogg" };

    private static int InstallRuntimeFiles(string dataDir)
    {
        string target = Path.Combine(dataDir, RuntimeFolder, "Audio");
        Directory.CreateDirectory(target);
        int copied = 0;
        foreach (string name in RuntimeAudio)
        {
            string source = Path.Combine(AppContext.BaseDirectory, "Audio", name);
            if (!File.Exists(source))
            {
                Console.ForegroundColor = ConsoleColor.Yellow;
                Console.WriteLine($"  missing: {source}");
                Console.ResetColor();
                continue;
            }
            File.Copy(source, Path.Combine(target, name), overwrite: true);
            copied++;
        }
        return copied;
    }

    // ==============================================================================
    // Finding the game
    // ==============================================================================

    /// <summary>Looks in the current folder and next to the program (the normal case when shipped in the game folder).</summary>
    private static string? FindDataDir()
    {
        foreach (string baseDir in new[] { Directory.GetCurrentDirectory(), AppContext.BaseDirectory })
        {
            string? found = ResolveDataDir(baseDir);
            if (found != null) return found;
        }
        return null;
    }

    /// <summary>
    /// Accepts the game folder or its data folder and returns the data folder (the one with "Managed" in it):
    /// Windows/Linux: "SpookyUnity_Data". macOS: "SpookyUnity.app/Contents/Resources/Data".
    /// </summary>
    private static string? ResolveDataDir(string path)
    {
        if (string.IsNullOrWhiteSpace(path)) return null;

        path = path.Trim().Trim('"').TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
        if (!Directory.Exists(path)) return null;

        if (Path.GetFileName(path).EndsWith("_Data", StringComparison.OrdinalIgnoreCase)
            || Directory.Exists(Path.Combine(path, "Managed")))
            return path;

        // macOS app bundle: the app itself, or the folder that contains it
        string? FromApp(string app)
        {
            string data = Path.Combine(app, "Contents", "Resources", "Data");
            return Directory.Exists(Path.Combine(data, "Managed")) ? data : null;
        }
        if (path.EndsWith(".app", StringComparison.OrdinalIgnoreCase)) return FromApp(path);

        string[] dirs = Directory.GetDirectories(path, "*_Data");
        if (dirs.Length == 1) return dirs[0];
        string[] apps = Directory.GetDirectories(path, "*.app");
        return apps.Length == 1 ? FromApp(apps[0]) : null;
    }

    /// <summary>Remembered folder, then the default Steam folders (asks to confirm), then asks for a path.</summary>
    private static string? AskForDataDir()
    {
        string savedFile = Path.Combine(AppContext.BaseDirectory, "gamepath.txt");

        // remembered from an earlier run
        if (File.Exists(savedFile))
        {
            string? remembered = ResolveDataDir(File.ReadAllText(savedFile));
            if (remembered != null) return remembered;
        }

        if (Console.IsInputRedirected) return null; // nobody to ask

        Console.WriteLine("The game was not found next to this program.");

        foreach (string candidate in DefaultGameFolders())
        {
            string? found = ResolveDataDir(candidate);
            if (found == null) continue;

            Console.WriteLine("Is the game installed here?");
            Console.WriteLine("  " + candidate);
            Console.Write("[Y/n]: ");
            string answer = (Console.ReadLine() ?? "").Trim().ToLowerInvariant();
            if (answer is "" or "y" or "yes")
            {
                Remember(savedFile, found);
                return found;
            }
            break; // they said no: do not offer the next default
        }

        while (true)
        {
            Console.Write("Enter the path of the game folder (empty to cancel): ");
            string input = (Console.ReadLine() ?? "").Trim();
            if (input.Length == 0) return null;

            string? found = ResolveDataDir(input);
            if (found != null)
            {
                Remember(savedFile, found);
                return found;
            }
            Console.WriteLine("The game's data folder (*_Data, or *.app on macOS) was not found there. Please try again.");
        }
    }

    private static void Remember(string savedFile, string dataDir)
    {
        try { File.WriteAllText(savedFile, dataDir); }
        catch { /* not being able to remember is fine */ }
    }

    private static void PrintUsage()
    {
        Console.WriteLine("SJSMHDBavarianPatcher");
        Console.WriteLine();
        Console.WriteLine("  SJSMHDBavarianPatcher                patch the game: assets, code, the mod's files (this is the default)");
        Console.WriteLine("  SJSMHDBavarianPatcher revert         restore the original game files");
        Console.WriteLine("  SJSMHDBavarianPatcher get <file> <pathId> [field] [--inner <name>]");
        Console.WriteLine("                                       print a field's current value, or the fields of the asset, e.g.");
        Console.WriteLine("                                       get level0 36            (lists the fields of that asset)");
        Console.WriteLine("                                       get sharedassets0.assets 21 m_Resource.m_Source");
        Console.WriteLine();
        Console.WriteLine("  --data \"<path>\"   the game folder or its *_Data folder. If omitted, the program looks next to itself,");
        Console.WriteLine("                    then asks (and remembers the answer in gamepath.txt)");
        Console.WriteLine("  --lz4             write bundles with LZ4 (fast, slightly bigger) instead of the original compression");
    }
}
